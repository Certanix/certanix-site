#!/usr/bin/env python3
"""Write the readable licence pages of /verify from the licence files in the wheel.

GitHub Pages serves LICENSE and NOTICE as application/octet-stream and PATENTS-NOTICE.md
as text/markdown, which browsers download (or, in Safari, refuse to show). So each file
also gets an HTML page in the /verify style, whose <pre> holds the file's text exactly:
the bytes in the wheel, HTML-escaped and nothing else. The raw files stay beside them as
downloads, with PATENTS-NOTICE.txt a plain-text copy of PATENTS-NOTICE.md.

The wheel is the one named in verify/runtime/verifier/bundle.json, checked against its
sha256 there. tools/build-verifier.sh runs this after placing a wheel; on its own:

    python3 tools/licence_pages.py

tools/test_licence_pages.py checks the result against the wheel and against PyPI.
"""

from __future__ import annotations

import hashlib
import html
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERIFY = ROOT / "verify"
LICENCE = VERIFY / "licence"
BUNDLE = VERIFY / "runtime" / "verifier" / "bundle.json"

#: (file in the wheel, its page, the page's title, what the page says the file is)
PAGES = (
    ("LICENSE", "licence.html", "LICENSE",
     "The BSD-3-Clause-Clear licence of certanix-verify"),
    ("NOTICE", "notice.html", "NOTICE",
     "Who holds the copyright in certanix-verify"),
    ("PATENTS-NOTICE.md", "patents.html", "PATENTS-NOTICE",
     "The patent notice of certanix-verify"),
)
#: Plain-text copies: (copy, the wheel file it repeats byte for byte)
COPIES = (("PATENTS-NOTICE.txt", "PATENTS-NOTICE.md"),)

PRE_OPEN = '<pre class="licence" id="text">'
PRE_CLOSE = "</pre>"


def wheel() -> tuple[Path, str, str]:
    """The verifier wheel named by bundle.json, its sha256 and its version."""
    bundle = json.loads(BUNDLE.read_text())
    [entry] = [w for w in bundle["wheels"] if w["file"].startswith("certanix_verify-")]
    path = BUNDLE.parent / entry["file"]
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != entry["sha256"]:
        sys.exit(f"{path.name}: sha256 {digest} is not the one in bundle.json")
    return path, digest, bundle["certanix_verify_version"]


def members(path: Path) -> dict[str, bytes]:
    """The licence files inside the wheel, by name."""
    with zipfile.ZipFile(path) as w:
        [meta] = [n for n in w.namelist() if n.endswith(".dist-info/METADATA")]
        base = meta.rsplit("/", 1)[0] + "/licenses/"
        return {name: w.read(base + name) for name, *_ in PAGES}


def page(name: str, html_name: str, title: str, what: str, text: bytes, version: str,
         wheel_name: str, digest: str) -> str:
    """One licence page. The text goes between PRE_OPEN and PRE_CLOSE, escaped only."""
    body = html.escape(text.decode("utf-8"), quote=False)
    plain = ""
    if name == "PATENTS-NOTICE.md":
        plain = ' &middot; <a href="PATENTS-NOTICE.txt">PATENTS-NOTICE (plain text)</a>'
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<!-- Generated by tools/licence_pages.py from the wheel. Do not edit by hand. -->
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'self'; img-src data:; base-uri 'none'; form-action 'none'">
<meta name="referrer" content="no-referrer">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · certanix-verify</title>
<meta name="description" content="{what} {version}, exactly as in the package on PyPI.">
<link rel="canonical" href="https://certanix.eu/verify/licence/{html_name}">
<meta name="theme-color" content="#0A0A0A">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E%3Crect width='64' height='64' fill='%230A0A0A'/%3E%3Cpath d='M 18 52 L 18 14 L 46 14 L 46 52' stroke='%23FFFFFF' stroke-width='6' fill='none' stroke-linecap='square'/%3E%3Crect x='24' y='40' width='14' height='5' fill='%23F5C518'/%3E%3C/svg%3E">
<link rel="stylesheet" href="../verify.css">
</head>
<body>

<div class="wrap">

  <header>
    <div class="registry"></div>
    <div class="lockup">
      <a href="/" aria-label="Certanix home">
        <svg class="mark" viewBox="-10 -22 157 258" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
          <path class="frame" d="M 0 220 L 0 0 L 130 0 L 130 220" stroke-width="14" stroke-linecap="square" fill="none"/>
          <rect class="latch" x="30" y="156" width="70" height="12"/>
          <line class="tick" x1="65" y1="-10" x2="65" y2="0" stroke-width="2"/>
        </svg>
        <span class="wordmark">CERTANI<span class="x">X</span></span>
      </a>
    </div>
    <h1 class="page-title">{title}</h1>
    <p class="lede">{what} {version}, exactly as in the package on PyPI.</p>
  </header>

  <section>
{PRE_OPEN}{body}{PRE_CLOSE}
    <p class="small">Download the file itself: <a href="{name}" download>{name}</a>{plain}.</p>
    <span class="label">From the wheel</span>
    <div class="mono">{wheel_name}<br>SHA-256 {digest}</div>
  </section>

  <div class="registry bottom"></div>

  <footer>
    <p>certanix-verify: <a href="licence.html">BSD-3-Clause-Clear</a> &middot; <a href="notice.html">NOTICE</a> &middot; <a href="patents.html">PATENTS-NOTICE</a>. <a href="/verify/">Verify a pack</a> &middot; <a href="/">certanix.eu</a></p>
  </footer>

</div>

</body>
</html>
"""


def render() -> dict[str, bytes]:
    """Every file this script writes into verify/licence/, by name."""
    path, digest, version = wheel()
    files = members(path)
    out = dict(files)
    for name, html_name, title, what in PAGES:
        out[html_name] = page(name, html_name, title, what, files[name], version,
                              path.name, digest).encode("utf-8")
    for copy, source in COPIES:
        out[copy] = files[source]
    return out


def pre_text(page_html: str) -> str:
    """The text a licence page shows: its <pre>, unescaped."""
    m = re.search(re.escape(PRE_OPEN) + r"(.*?)" + re.escape(PRE_CLOSE), page_html, re.S)
    if not m:
        raise ValueError("no licence text in the page")
    return html.unescape(m.group(1))


def main() -> None:
    LICENCE.mkdir(parents=True, exist_ok=True)
    for name, data in render().items():
        (LICENCE / name).write_bytes(data)
        print(f"verify/licence/{name}  {hashlib.sha256(data).hexdigest()}")


if __name__ == "__main__":
    main()
